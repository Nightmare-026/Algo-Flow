import { Algorithm } from "@/types";

type CatalogAlgorithmInput = {
  id: string;
  operationId: string;
  dataStructureId: string;
  name: string;
  slug: string;
  difficulty?: Algorithm["difficulty"];
  average?: string;
  worst?: string;
  space?: string;
  shortDescription: string;
  tags?: string[];
  visualizerType: string;
  priority?: Algorithm["priority"];
  prerequisites?: string[];
};

function catalogAlgorithm(input: CatalogAlgorithmInput): Algorithm {
  return {
    id: input.id,
    operationId: input.operationId,
    dataStructureId: input.dataStructureId,
    name: input.name,
    slug: input.slug,
    difficulty: input.difficulty ?? "medium",
    timeComplexityBest: input.average ?? "O(n)",
    timeComplexityAverage: input.average ?? "O(n)",
    timeComplexityWorst: input.worst ?? input.average ?? "O(n)",
    spaceComplexity: input.space ?? "O(1)",
    shortDescription: input.shortDescription,
    longDescription: `${input.name} is included in the Algo Flow content catalog so learners can discover the topic and track it as the visualizer library grows.`,
    prerequisites: input.prerequisites ?? [],
    tags: input.tags ?? [],
    visualizerType: input.visualizerType,
    priority: input.priority ?? "P1",
    isPublished: true,
  };
}

